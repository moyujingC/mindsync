def get_color_interpretation(element: str, shade: str, circle: str) -> Optional[Dict]:
    """
    获取特定颜色在特定圈层的解读

    Args:
        element: 五行元素（木/火/土/金/水）
        shade: 颜色深浅（如深绿、中红、淡黄）
        circle: 圈层（内圈/中圈/外圈）

    Returns:
        解读字典，未找到返回None
    """
    element_data = COLOR_MEANINGS.get(element)
    if not element_data:
        return None

    shades = element_data.get("shades", {})
    shade_data = shades.get(shade)
    if not shade_data:
        return None

    circle_data = shade_data.get("circles", {}).get(circle)
    if not circle_data:
        return None

    return {
        "element": element,
        "shade": shade,
        "circle": circle,
        "interpretation": circle_data.get("interpretation"),
        "manifestations": circle_data.get("manifestations", []),
        "healing": circle_data.get("healing", ""),
    }


