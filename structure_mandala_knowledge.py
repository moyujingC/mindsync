def extract_content(content):
    """提取纯文本内容，移除时间戳和说话人标记"""
    lines = content.split('\n')
    result_lines = []

    for line in lines:
        line = line.strip()
        # 跳过空行、标题行（音频文件名）
        if not line or line.startswith('2022-') or line.startswith('##'):
            continue
        # 移除时间戳格式的行: "1号讲话人  00:00:00"
        if re.match(r'^\d号讲话人\s+\d{2}:\d{2}:\d{2}$', line):
            continue
        # 移除孤立的时间戳
        if re.match(r'^\d{2}:\d{2}:\d{2}$', line):
            continue
        result_lines.append(line)

    return '\n'.join(result_lines)

def split_by_sections(text, min_para_length=100):
    """将文本按段落分割，过滤短段落"""
    paragraphs = []
    current = []

    for line in text.split('\n'):
        line = line.strip()
        if not line:
            if current:
                para = ' '.join(current)
                if len(para) >= min_para_length:
                    paragraphs.append(para)
                current = []
        else:
            current.append(line)

    if current:
        para = ' '.join(current)
        if len(para) >= min_para_length:
            paragraphs.append(para)

    return paragraphs

