def extract_meaningful_segments(text, min_length=80):
    """提取有意义的段落，过滤短段落和过渡段"""
    paragraphs = []
    current = []
    current_len = 0

    # 过滤串场词和口头禅
    filler_patterns = [
        r'^(好|那|我们|首先|其次|另外|接下来)\s*,?\s*',  # 开头过渡词
        r'各位小宝贝们',  # 打招呼
        r'我来说一下',
        r'就是[，,]',
        r'好不好[？?]',
        r'对不对[？?]',
        r'大家能懂吗',
        r'你们说',
        r'知道吗',
        r'明白了吗',
        r'听懂了[吗没]',
        r'没关系',
        r'慢慢来',
        r'不着急',
        r'好不好',
        r'我们先',
        r'下课',
        r'休息',
        r'上课',
        r'今天|昨天|明天|第三天|第四天',
        r'时间过得',
        r'好，我们',
        r'那我们',
        r'好，那',
        r'爱你',  # 结束语
        r'么么哒',
        r'好嘞',
        r'好啦',
        r'那好',
    ]

    def is_filler(text):
        for pattern in filler_patterns:
            if re.match(pattern, text):
                return True
        return False

    for line in text.split('\n'):
        if not line:
            if current:
                para = ' '.join(current)
                # 过滤太短的、纯过渡的
                if len(para) >= min_length:
                    # 过滤开头是过渡词的
                    first_sentence = para.split('，')[0].split('，')[0]
                    if not is_filler(first_sentence[:10]):
                        paragraphs.append(para)
                current = []
                current_len = 0
        else:
            current.append(line)
            current_len += len(line)

    if current:
        para = ' '.join(current)
        if len(para) >= min_length:
            paragraphs.append(para)

    return paragraphs

