def clean_text(text):
    """清理文本"""
    lines = text.split('\n')
    result_lines = []

    for line in lines:
        line = line.strip()
        if not line or line.startswith('2022-') or line.startswith('##'):
            continue
        # 移除时间戳标记
        if re.match(r'^\d号讲话人\s+\d{2}:\d{2}:\d{2}$', line):
            continue
        result_lines.append(line)

    return '\n'.join(result_lines)

